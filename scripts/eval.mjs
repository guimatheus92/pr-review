// Eval harness for the review pipeline (issue #5): run known diffs through the
// REAL pipeline (packs + stack detection + pass selection + a live runtime) and
// assert that the findings contain what a competent review must find.
//
//   node scripts/eval.mjs [case] [-- extra review argv, e.g. --runtime claude]
//
// Prereqs: `npm run build` (uses dist/cli.cjs, the artifact users run), a
// runtime CLI on PATH (copilot or claude), and `pr-review packs sync` done at
// least once (the passes come from the synced packs). Manual/pre-release — not
// part of `npm run test` (scripts/test.mjs only walks tests/).
//
// Each fixture: evals/fixtures/<case>/diff.patch + expected.yaml
//   expected.yaml: { must_find: [regex, ...], pass?: <name or suffix> }
// Every regex (case-insensitive) must match `title\n body` of at least one
// finding — in the named pass when `pass` is given, anywhere otherwise.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from 'yaml';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const CLI = join(ROOT, 'dist', 'cli.cjs');
const FIXTURES = join(ROOT, 'evals', 'fixtures');
const PLACEHOLDER_PR = 'https://github.com/pr-review/eval/pull/1';

function parseArgs(argv) {
  const sep = argv.indexOf('--');
  const own = sep === -1 ? argv : argv.slice(0, sep);
  const extra = sep === -1 ? [] : argv.slice(sep + 1);
  return { caseName: own[0], extra };
}

/** diff.patch → GatherOutput-shaped JSON (metadata fabricated to satisfy earlyExitGate). */
function gatherFromPatch(patchText) {
  const files = [];
  const fileRe = /^diff --git a\/(.+?) b\/(.+)$/gm;
  const starts = [];
  let m;
  while ((m = fileRe.exec(patchText)) !== null) starts.push({ path: m[2], index: m.index });
  if (starts.length === 0) throw new Error('diff.patch has no `diff --git` headers');
  for (let i = 0; i < starts.length; i++) {
    const chunk = patchText.slice(starts[i].index, starts[i + 1]?.index ?? patchText.length);
    const hunkStart = chunk.indexOf('@@');
    const patch = hunkStart === -1 ? chunk : chunk.slice(hunkStart);
    const additions = (patch.match(/^\+(?!\+\+)/gm) ?? []).length;
    const deletions = (patch.match(/^-(?!--)/gm) ?? []).length;
    files.push({ path: starts[i].path, status: 'modified', additions, deletions, patch: patch.trimEnd() });
  }
  return {
    pr: { provider: 'github', url: PLACEHOLDER_PR, owner: 'pr-review', repo: 'eval', number: 1 },
    metadata: {
      title: 'Eval fixture PR',
      description: 'Synthetic PR generated by scripts/eval.mjs from a fixture diff.',
      author: 'eval-harness',
      headSha: 'e'.repeat(40),
      baseSha: 'b'.repeat(40),
      baseBranch: 'main',
      headBranch: 'eval-fixture',
      labels: [],
      linkedItems: [],
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
      isDraft: false,
      state: 'open',
    },
    changedFiles: files,
    fullDiff: patchText,
    existingComments: [],
    gatheredAt: new Date().toISOString(),
  };
}

function runCase(name, extra) {
  const dir = join(FIXTURES, name);
  const patchText = readFileSync(join(dir, 'diff.patch'), 'utf8');
  const expected = parseYaml(readFileSync(join(dir, 'expected.yaml'), 'utf8'));
  const runDir = mkdtempSync(join(tmpdir(), `pr-review-eval-${name}-`));
  const gatherFile = join(runDir, 'eval-gather.json');
  writeFileSync(gatherFile, JSON.stringify(gatherFromPatch(patchText), null, 2), 'utf8');

  const argv = [CLI, 'review', PLACEHOLDER_PR, '--from-gather', gatherFile, '--dry-run', '--no-cache', '--run-dir', runDir, ...extra];
  console.log(`\n=== ${name} ===`);
  let exitCode = 0;
  try {
    execFileSync(process.execPath, argv, { stdio: ['ignore', 'inherit', 'inherit'], timeout: 30 * 60 * 1000 });
  } catch (err) {
    exitCode = err.status ?? 1;
  }

  const findingsPath = join(runDir, 'pr-review-findings.json');
  if (!existsSync(findingsPath)) {
    console.error(`✗ ${name}: no pr-review-findings.json (review exit ${exitCode}) — run \`pr-review packs sync\` first? artifacts: ${runDir}`);
    return false;
  }
  const findings = JSON.parse(readFileSync(findingsPath, 'utf8'));
  const inScope = expected.pass
    ? (findings.reviewers ?? [])
        .filter((r) => r.reviewer === expected.pass || r.reviewer.endsWith(`/${expected.pass}`))
        .flatMap((r) => r.findings)
    : (findings.finalFindings ?? []);

  let ok = true;
  const patterns = expected?.must_find;
  if (!Array.isArray(patterns) || patterns.length === 0) {
    console.error(`  x ${name}: expected.yaml has no must_find patterns - a fixture that asserts nothing proves nothing`);
    return false;
  }
  for (const pattern of patterns) {
    const re = new RegExp(pattern, 'i');
    const hit = inScope.find((f) => re.test(`${f.title}\n${f.body}`));
    if (hit) {
      console.log(`  ✓ /${pattern}/ → "${hit.title}"`);
    } else {
      console.error(`  ✗ /${pattern}/ not found in ${inScope.length} finding(s)${expected.pass ? ` of pass ${expected.pass}` : ''}`);
      ok = false;
    }
  }
  if (ok) rmSync(runDir, { recursive: true, force: true });
  else console.error(`  artifacts kept at ${runDir}`);
  return ok;
}

const { caseName, extra } = parseArgs(process.argv.slice(2));
if (!existsSync(CLI)) {
  console.error('dist/cli.cjs not found — run `npm run build` first.');
  process.exit(1);
}
const cases = caseName ? [caseName] : readdirSync(FIXTURES);
let failures = 0;
for (const c of cases) {
  if (!runCase(c, extra)) failures++;
}
console.log(failures === 0 ? `\nall ${cases.length} eval case(s) passed` : `\n${failures}/${cases.length} eval case(s) FAILED`);
process.exit(failures === 0 ? 0 : 1);
